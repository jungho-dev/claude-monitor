// 5. 자리표시자 채움 ----------------------------------------------------------
// `{0}`, `{1}` 을 한 번에 치환 (치환된 값 안의 중괄호는 다시 해석하지 않음)
pub fn fill_template(template: &str, values: &[&str]) -> String {
    let mut filled = String::with_capacity(template.len() + 16);
    let mut rest = template;
    while let Some(open) = rest.find('{') {
        let after_open = &rest[open + 1..];
        let slot = after_open
            .find('}')
            .and_then(|close| after_open[..close].parse::<usize>().ok())
            .and_then(|index| values.get(index));
        match slot {
            Some(value) => {
                filled.push_str(&rest[..open]);
                filled.push_str(value);
                let close = after_open.find('}').unwrap_or(0);
                rest = &after_open[close + 1..];
            }
            None => {
                filled.push_str(&rest[..=open]);
                rest = after_open;
            }
        }
    }
    filled.push_str(rest);
    filled
}
